training_tree<-read.nexus(input_path('training_timetree.nexus'))
training_meta<-read_tree_metadata(input_path('training_tree_metadata.csv'))
check(!anyDuplicated(training_tree$tip.label)&!anyDuplicated(training_meta$name),'Training tree and metadata identifiers unique')
check(all(training_tree$tip.label %in% training_meta$name),'Every training-tree tip matched to metadata after BOM repair')
check(all(is.finite(training_tree$edge.length))&all(training_tree$edge.length>=0),'Training-tree branch lengths finite and nonnegative')
tm<-training_meta[match(training_tree$tip.label,training_meta$name),]
host_levels<-sort(unique(label_missing(tm$host)));host_cols<-setNames(rep(palette_ceri,length.out=length(host_levels)),host_levels)
for(ext in c('png','pdf')){
 if(ext=='png')png('results/figures/training_tree_hosts.png',width=3000,height=2300,res=240) else pdf('results/figures/training_tree_hosts.pdf',width=12.5,height=9.6)
 par(mar=c(3,2,4,2),xpd=NA)
 plot(training_tree,type='fan',use.edge.length=FALSE,show.tip.label=FALSE,tip.color=host_cols[label_missing(tm$host)],edge.color='#667784',edge.width=1.1,no.margin=FALSE)
 tiplabels(pch=19,col=host_cols[label_missing(tm$host)],cex=.55)
 title('Host annotation of the supplied training tree',cex.main=1.3)
 mtext('256 supplied tips; topology view, branch lengths not drawn to scale; tree not re-inferred',side=1,line=1,cex=.8)
 legend('topleft',legend=host_levels,col=host_cols,pch=19,bty='n',cex=.9)
 dev.off()
}
host_summary<-as.data.frame(table(host=label_missing(tm$host)));names(host_summary)[2]<-'tips';write_table(host_summary,'training_tree_host_summary')
tree<-read.tree(input_path('Shigella_tree.txt'))
meta<-read.csv(input_path('sample_data_Shigella_tree.csv'))
check(!anyDuplicated(tree$tip.label)&!anyDuplicated(meta$Sample_ID),'Shigella tip and metadata identifiers unique')
check(all(tree$tip.label %in% meta$Sample_ID),'Every Shigella tree tip matched to metadata')
check(all(is.finite(tree$edge.length))&all(tree$edge.length>=0),'Shigella branch lengths finite and nonnegative')
meta<-meta[match(tree$tip.label,meta$Sample_ID),]
continents<-sort(unique(label_missing(meta$Continent)));cc<-setNames(palette_ceri[seq_along(continents)],continents)
macrolide_recorded<-!is.na(meta$macrolide_resistance_genes)&nzchar(trimws(meta$macrolide_resistance_genes))
for(ext in c('png','pdf')){
 if(ext=='png')png('results/figures/shigella_phylogeny.png',width=3000,height=2500,res=240) else pdf('results/figures/shigella_phylogeny.pdf',width=12.5,height=10.4)
 par(mar=c(3,2,4,2),xpd=NA)
 plot(tree,type='fan',use.edge.length=FALSE,show.tip.label=FALSE,edge.color='#657785',edge.width=1.1,no.margin=FALSE)
 tiplabels(pch=21,bg=cc[label_missing(meta$Continent)],col=ifelse(macrolide_recorded,'#182b49','white'),cex=.65,lwd=1)
 title('Shigella sonnei phylogeny with surveillance metadata',cex.main=1.25)
 mtext('Topology view (branch lengths not to scale); dark outlines mark recorded macrolide-resistance genes',side=1,line=1,cex=.8)
 legend('topleft',legend=continents,pch=21,pt.bg=cc,col='#657785',bty='n',cex=.9)
 dev.off()
}
continent_summary<-meta %>% group_by(Continent) %>% summarise(tips=n(),macrolide_gene_recorded=sum(!is.na(macrolide_resistance_genes)&nzchar(macrolide_resistance_genes)),.groups='drop')
write_table(continent_summary,'shigella_continent_summary')
pdf('results/figures/full_branch_length_phylograms.pdf',width=12,height=18)
par(mar=c(3,2,3,2))
plot(training_tree,show.tip.label=FALSE,edge.width=.6);tiplabels(pch=19,col=host_cols[label_missing(tm$host)],cex=.35)
title('Supplied training tree: original branch lengths');add.scale.bar()
plot(tree,show.tip.label=FALSE,edge.width=.6);tiplabels(pch=19,col=cc[label_missing(meta$Continent)],cex=.35)
title('Published Shigella tree: original branch lengths');add.scale.bar()
dev.off()
write_table(data.frame(dataset=c('Training tree','Shigella'),tree_tips=c(Ntip(training_tree),Ntip(tree)),metadata_rows=c(nrow(training_meta),nrow(meta)),matched_tips=c(nrow(tm),nrow(meta)),unused_metadata=c(sum(!training_meta$name %in% training_tree$tip.label),0)),'phylogeny_matching')
metrics$phylogeny<-list(training_tips=Ntip(training_tree),training_metadata=nrow(training_meta),training_extra_metadata=sum(!training_meta$name %in% training_tree$tip.label),training_hosts=length(host_levels),shigella_tips=Ntip(tree),shigella_countries=n_distinct(meta$Country),macrolide_gene_recorded=sum(macrolide_recorded))


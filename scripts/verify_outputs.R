args<-commandArgs(trailingOnly=FALSE);fa<-sub('^--file=','',args[grepl('^--file=',args)])
if(length(fa))setwd(normalizePath(file.path(dirname(fa),'..'),winslash='/'))
library(jsonlite);library(digest)
manifest<-read.csv('references/input_manifest.csv')
stopifnot(all(file.exists(manifest$file)))
actual<-vapply(manifest$file,function(f)digest(file=f,algo='sha256'),character(1))
stopifnot(identical(unname(actual),manifest$sha256))
m<-fromJSON('results/tables/run_summary.json');qc<-read.csv('results/tables/qc_checks.csv')
stopifnot(all(qc$passed),m$variants$records==801,m$variants$samples==3,m$phylogeny$training_tips==256,m$phylogeny$shigella_tips==299,m$outbreak$cases==5888)
outcomes<-read.csv('results/tables/outbreak_outcomes.csv');weekly<-read.csv('results/tables/weekly_onset_cases.csv')
stopifnot(sum(outcomes$cases)==m$outbreak$cases,sum(weekly$cases)+m$outbreak$onset_missing==m$outbreak$cases)
stopifnot(m$outbreak$matched_endpoint_links+m$outbreak$unmatched_endpoint_links==m$outbreak$recorded_links)
readme<-paste(readLines('README.md',warn=FALSE),collapse='\n')
paths<-regmatches(readme,gregexpr('results/figures/[A-Za-z0-9_.-]+[.]png',readme))[[1]]
stopifnot(length(paths)>0,all(file.exists(paths)),!grepl('{{',readme,fixed=TRUE))
required<-c('results/reports/surveillance_report.html','results/reports/outbreak_dashboard.html','results/figures/full_branch_length_phylograms.pdf')
stopifnot(all(file.exists(required)),all(file.info(required)$size>1000))
write_json(list(input_files_verified=nrow(manifest),analysis_QC_checks=nrow(qc),readme_figures_verified=length(paths),report_files_verified=length(required),passed=TRUE),'results/tables/verification_summary.json',pretty=TRUE,auto_unbox=TRUE)
cat('Verified input hashes, reference dataset counts, accounting identities, README figures and rendered reports.\n')
